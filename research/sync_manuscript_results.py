"""Refresh the IEEE draft's result macros and review image from completed runs."""

import json
from pathlib import Path
import shutil

RESEARCH = Path(__file__).resolve().parent
RUN = RESEARCH.parent / "results/research_20261125"
DRAFT = RESEARCH / "IEEE_CrownTrace_2026"


def read(path):
    return json.loads(path.read_text(encoding="utf-8"))


def sync():
    trees = read(RUN / "roboflow_test/summary.json")
    scores = trees["test"]
    masks = scores["metrics"]["network"]
    variant = read(RUN / "roboflow_multiscale_test/summary.json")
    transfer = read(RUN / "mask_cross_source_mopad/summary.json")["results"]["test"]
    pilot = read(RUN / "mask_comparison/summary.json")["results"]["test"]
    condition = read(RUN / "condition_ablation/summary.json")["methods"]
    siit = read(RUN / "detection_test/summary.json")["metrics"]["test"]
    prep = read(RESEARCH.parent / "data/roboflow_crowns_grouped_v1/preparation.json")
    rgb, masked = condition["rgb_box"], condition["predicted_mask"]
    values = {
        "SourceCrossVisual": prep["visual_clusters_cross_original_splits"],
        "TreeMAE": scores["count_mae_per_tile"], "TreeBias": scores["count_bias_per_tile"],
        "CountCut": trees["count_cutoff"], "TreesPredicted": scores["point_detections"],
        "MaskPrecision": masks["precision50_at_count_threshold"], "MaskRecall": masks["recall50_at_count_threshold"],
        "MaskGain": masks["ap50_95"] - scores["metrics"]["mean_shape"]["ap50_95"],
        "MaskOracle": scores["oracle_box_mean_iou"]["network"],
        "EllipseOracle": scores["oracle_box_mean_iou"]["ellipse"], "PriorOracle": scores["oracle_box_mean_iou"]["mean_shape"],
        "TransferOracle": transfer["oracle_box_iou"], "TransferDetected": transfer["detector_prompt_iou"],
        "PilotOracle": pilot["oracle_box_iou"], "PilotDetected": pilot["detector_prompt_iou"],
        "MopadPriorOracle": pilot["shape_prior_iou"], "MopadPriorDetected": pilot["detector_prior_iou"],
        "SiitBoxAP": siit["full_640"]["crown_ap50"], "SiitMAE": siit["full_640"]["count_mae"],
        "SiitClassAP": siit["full_640"]["condition_macro_ap50"], "SiitHighMAE": siit["full_1024"]["count_mae"],
        "RGBFone": rgb["test_macro_f1_mean"], "RGBSD": rgb["test_macro_f1_sd"],
        "MaskedFone": masked["test_macro_f1_mean"], "MaskedSD": masked["test_macro_f1_sd"],
        "ConditionGain": masked["test_macro_f1_mean"] - rgb["test_macro_f1_mean"],
        "BaseValMaskAP": trees["val"]["metrics"]["network"]["ap50_95"],
        "MultiValMaskAP": variant["val"]["metrics"]["network"]["ap50_95"],
        "MultiTreeMAE": variant["test"]["count_mae_per_tile"],
    }
    for key, name in zip(("boxes", "rectangle", "ellipse", "mean_shape", "network"),
                         ("Box", "Rect", "Ellipse", "Prior", "Mask"), strict=True):
        for suffix, metric in zip(("APFifty", "APSeventy", "APMean"), ("ap50", "ap75", "ap50_95"), strict=True):
            values[name + suffix] = scores["metrics"][key][metric]
            if key == "network":
                values["MultiMask" + suffix] = variant["test"]["metrics"][key][metric]
    for letter, raw, cut in zip("ABC", rgb["runs"], masked["runs"], strict=True):
        values["Rgb" + letter], values["Mask" + letter] = raw["test"]["macro_f1"], cut["test"]["macro_f1"]
    lines = ["% Values generated by sync_manuscript_results.py"]
    for key, value in values.items():
        number = str(value) if isinstance(value, int) else f"{value:.3f}"
        if isinstance(value, float) and (key.endswith("MAE") or key in ("TreeBias", "CountCut")):
            number = f"{value:.2f}"
        lines.append(r"\newcommand" + "{" + "\\" + key + "}{" + number + "}")
    (DRAFT / "results.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")
    shutil.copyfile(RUN / "roboflow_test/test_tile_11.png", DRAFT / "tile_review.png")


if __name__ == "__main__":
    sync()
