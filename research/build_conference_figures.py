"""Regenerate the manuscript numbers and the grid-origin figure from verified results."""
from pathlib import Path
import json

from reportlab.lib.colors import HexColor, white
from reportlab.pdfbase import pdfmetrics
from reportlab.pdfbase.ttfonts import TTFont
from reportlab.pdfgen.canvas import Canvas

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "research/overleaf_boundary_draft"
POINTS = ROOT / "results/registered_origin_pilot/summary.json"
MASKS = ROOT / "results/segment_validation/summary.json"


def read(path):
    return json.loads(path.read_text(encoding="utf-8"))


def f1_percent(method):
    return 200 * method["tp"] / (method["reference"] + method["predicted"])


def measured(points, masks):
    test = points["results"]["test"]["methods"]
    val = points["results"]["val"]["methods"]
    base, score, core = (test[name] for name in ("no_overlap", "overlap_score", "overlap_core"))
    mask = masks["results"]["test"]
    metrics = {
        "RefN": score["reference"], "SeamRef": score["seam_reference"],
        "MatchRadius": f'{points["match_radius_px"]:.1f}',
        "NearDuplicate": score["unmatched_within_radius_of_reference"],
        "CoreGain": f'{f1_percent(core) - f1_percent(score):+.2f}',
        "MaskDetectorGain": f'{mask["detector_prompt_iou"] - mask["detector_prior_iou"]:.3f}',
        "MaskMatched": mask["detector_prompt_matches"],
        "ValBaseF": f'{f1_percent(val["no_overlap"]):.2f}',
        "ValScoreF": f'{f1_percent(val["overlap_score"]):.2f}',
    }
    for name, method in (("Base", base), ("Score", score), ("Core", core)):
        fields = {"FP": "fp", "FN": "fn", "TP": "tp", "N": "predicted", "Windows": "windows",
                  "BoundaryMatches": "seam_matched"}
        metrics.update({name + k: method[v] for k, v in fields.items()})
        metrics[name + "F"] = f'{f1_percent(method):.2f}'
        metrics[name + "Boundary"] = f'{100 * method["seam_matched"] / method["seam_reference"]:.2f}'
        metrics[name + "Precision"] = f'{100 * method["tp"] / method["predicted"]:.2f}'
        metrics[name + "Time"] = f'{method["compute_s"]:.2f}'
    for tag, key in (("OracleIoU", "oracle_box_iou"), ("EllipseIoU", "ellipse_iou"),
                     ("PriorIoU", "shape_prior_iou"), ("DetectedIoU", "detector_prompt_iou"),
                     ("EllipseDetected", "detector_ellipse_iou"), ("PriorDetected", "detector_prior_iou")):
        metrics[tag] = f"{mask[key]:.3f}"
    return metrics


def origin_figure(path, data):
    font = "Times-Roman"
    local = Path("C:/Windows/Fonts/times.ttf")
    if local.is_file():
        font = "ChartTimes"
        pdfmetrics.registerFont(TTFont(font, str(local)))
    width, height = 244, 147
    canvas = Canvas(str(path), pagesize=(width, height), initialFontName=font)
    canvas.setTitle("Boundary-band recall across shifted grids")
    canvas.setFillColor(white)
    canvas.rect(0, 0, width, height, stroke=0, fill=1)
    dark = HexColor("#182e29")
    teal = HexColor("#176c58")
    ochre = HexColor("#9d5605")
    left, right = 54, 234

    def x(value):
        return left + (value - .60) / .40 * (right - left)

    canvas.setFont(font, 9)
    canvas.setFillColor(dark)
    canvas.drawString(3, 125, "Grid shift (px)")
    canvas.drawCentredString((left + right) / 2, 7, "Boundary-band recall")
    for value in (.6, .7, .8, .9, 1.):
        px = x(value)
        canvas.setStrokeColor(HexColor("#d5e2db"))
        canvas.setLineWidth(.55)
        canvas.line(px, 32, px, 119)
        canvas.setFillColor(dark)
        canvas.drawCentredString(px, 21, f"{value:.1f}")
    for index, row in enumerate(data):
        y = 109 - 21 * index
        ex, ey = row.get("origin_shift_px", [0, 0])
        base = row["methods"]["no_overlap"]["seam_recall"]
        overlap = row["methods"]["overlap_score"]["seam_recall"]
        canvas.setFillColor(dark)
        canvas.drawRightString(46, y-3, f"{ex}, {ey}")
        canvas.setStrokeColor(HexColor("#8fa59a"))
        canvas.setLineWidth(1.1)
        canvas.line(x(base), y, x(overlap), y)
        canvas.setFillColor(ochre)
        canvas.rect(x(base) - 3, y - 3, 6, 6, stroke=0, fill=1)
        canvas.setFillColor(teal)
        canvas.circle(x(overlap), y, 3.3, stroke=0, fill=1)
    canvas.setFont(font, 8.8)
    canvas.setFillColor(ochre)
    canvas.rect(58, 134, 5.5, 5.5, stroke=0, fill=1)
    canvas.setFillColor(dark)
    canvas.drawString(67, 133, "No overlap")
    canvas.setFillColor(teal)
    canvas.circle(132, 137, 3, stroke=0, fill=1)
    canvas.setFillColor(dark)
    canvas.drawString(140, 133, "Overlap + score")
    canvas.save()


def main():
    points, masks = read(POINTS), read(MASKS)
    values = measured(points, masks)
    (SOURCE / "measured_values.tex").write_text(
        "% Generated by research/build_conference_figures.py\n" +
        "\n".join(rf"\newcommand{{\{key}}}{{{value}}}" for key, value in values.items()) + "\n",
        encoding="utf-8")
    test = points["results"]["test"]
    origin_figure(SOURCE / "figures/grid_sensitivity.pdf", [test, *test["origin_audit"]])


if __name__ == "__main__":
    main()
